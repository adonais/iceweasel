static void ImportCertAndKey(PK11SlotInfo* slot, const uint8_t* certData,
                             unsigned int certLen, const uint8_t* keyData,
                             unsigned int keyLen, const char* nickname) {
  SECItem pkcs8Item = {siBuffer, const_cast<unsigned char*>(keyData), keyLen};
  SECKEYPrivateKey* privKey = nullptr;
  SECStatus rv = PK11_ImportDERPrivateKeyInfoAndReturnKey(
      slot, &pkcs8Item, nullptr, nullptr, true, false, KU_ALL, &privKey,
      nullptr);
  assert(rv == SECSuccess);
  assert(privKey);

  SECItem certItem = {siBuffer, const_cast<unsigned char*>(certData), certLen};
  CERTCertDBHandle* certDB = CERT_GetDefaultCertDB();
  ScopedCERTCertificate cert(
      CERT_NewTempCertificate(certDB, &certItem, nullptr, false, true));
  assert(cert);

  rv = PK11_ImportCert(slot, cert.get(), privKey->pkcs11ID, nickname, PR_FALSE);
  assert(rv == SECSuccess);

  SECKEY_DestroyPrivateKey(privKey);
}

// Callback for EncryptedData decryption. Generates a symmetric key matching
// the requested algorithm so the decoder can exercise the decryption path
// even on fuzz-mutated EncryptedData structures.
static PK11SymKey* DecryptKeyCallback(void* arg, SECAlgorithmID* algid) {
  SECOidTag algtag = SECOID_GetAlgorithmTag(algid);
  CK_MECHANISM_TYPE mechanism = PK11_AlgtagToMechanism(algtag);
  if (mechanism == CKM_INVALID_MECHANISM) {
    mechanism = CKM_AES_CBC;
  }

  PK11SlotInfo* slot = PK11_GetBestSlot(mechanism, nullptr);
  if (!slot) {
    slot = PK11_GetInternalSlot();
  }
  if (!slot) {
    return nullptr;
  }

  // Generate a random key. The decryption will produce garbage but that's
  // fine — we're fuzzing the cipher machinery, not the plaintext.
  PK11SymKey* key = PK11_KeyGen(slot, mechanism, nullptr, 16, nullptr);
  PK11_FreeSlot(slot);
  return key;
}

// Exercise the streaming decoder path (Decoder_Start / Update / Finish or
// Cancel) in addition to NSS_CMSMessage_CreateFromDER. This adds coverage
// for chunked Update and the Cancel cleanup path. Also fuzzes nss_cms_decoder
// state machine transitions that don't fire in single-shot decode.
static void TryStreamingDecode(const uint8_t* data, size_t size) {
  NSSCMSDecoderContext* dcx = NSS_CMSDecoder_Start(
      nullptr, nullptr, nullptr, nullptr, nullptr, DecryptKeyCallback, nullptr);
  if (!dcx) {
    return;
  }

  // Feed the input in 4 chunks to exercise the chunked Update path.
  size_t chunk = (size / 4) + 1;
  size_t off = 0;
  bool failed = false;
  while (off < size) {
    size_t n = chunk < (size - off) ? chunk : (size - off);
    if (NSS_CMSDecoder_Update(dcx, (const char*)data + off, n) != SECSuccess) {
      failed = true;
      break;
    }
    off += n;
  }

  // Use the first byte to choose between Cancel and Finish so both cleanup
  // paths get exercised by the corpus.
  if (failed || (data[0] & 1)) {
    NSS_CMSDecoder_Cancel(dcx);
  } else {
    ScopedNSSCMSMessage cmsg(NSS_CMSDecoder_Finish(dcx));
  }
}

// RAII wrapper so NSS_Shutdown runs at process exit. Without it, the global
// trust domain allocated by NSS_InitReadWrite is reported as a leak.
class SmimeFuzzerNSS {
 public:
  SmimeFuzzerNSS() {
    char tmpl[] = "/tmp/smime_fuzzdb_XXXXXX";
    char* dbdir = mkdtemp(tmpl);
    assert(dbdir);

    char configdir[256];
    snprintf(configdir, sizeof(configdir), "sql:%s", dbdir);
    assert(NSS_InitReadWrite(configdir) == SECSuccess);

    ScopedPK11SlotInfo slot(PK11_GetInternalKeySlot());
    assert(slot);

    assert(PK11_NeedUserInit(slot.get()));
    assert(PK11_InitPin(slot.get(), nullptr, "") == SECSuccess);

    ImportCertAndKey(slot.get(), kSmimeFuzzCert, sizeof(kSmimeFuzzCert),
                     kSmimeFuzzKey, sizeof(kSmimeFuzzKey), "SMIME Fuzz Test");
    ImportCertAndKey(slot.get(), kSmimeFuzzEcCert, sizeof(kSmimeFuzzEcCert),
                     kSmimeFuzzEcKey, sizeof(kSmimeFuzzEcKey), "SMIME Fuzz EC");
  }
  ~SmimeFuzzerNSS() { (void)NSS_Shutdown(); }
};

extern "C" int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
  static SmimeFuzzerNSS nss;
  (void)nss;

  if (size == 0) {
    return 0;
  }

  TryStreamingDecode(data, size);

  SECItem buffer = {siBuffer, (unsigned char*)data, (unsigned int)size};

  ScopedNSSCMSMessage cmsg(
      NSS_CMSMessage_CreateFromDER(&buffer, nullptr, nullptr, nullptr, nullptr,
                                   DecryptKeyCallback, nullptr));
  (void)NSS_CMSMessage_IsSigned(cmsg.get());
  (void)NSS_CMSMessage_IsEncrypted(cmsg.get());

  int levels = NSS_CMSMessage_ContentLevelCount(cmsg.get());
  for (int i = 0; i < levels; ++i) {
    NSSCMSContentInfo* cinfo = NSS_CMSMessage_ContentLevel(cmsg.get(), i);
    SECOidTag tag = NSS_CMSContentInfo_GetContentTypeTag(cinfo);

    (void)NSS_CMSContentInfo_GetContentTypeOID(cinfo);
    (void)NSS_CMSContentInfo_GetContentEncAlgTag(cinfo);
    (void)NSS_CMSContentInfo_GetContentEncAlg(cinfo);
    (void)NSS_CMSContentInfo_GetBulkKeySize(cinfo);
    (void)NSS_CMSContentInfo_GetChildContentInfo(cinfo);

    if (tag == SEC_OID_PKCS7_SIGNED_DATA) {
      NSSCMSSignedData* signedData =
          (NSSCMSSignedData*)NSS_CMSContentInfo_GetContent(cinfo);
      if (!signedData) {
        continue;
      }

      (void)NSS_CMSSignedData_GetDigestAlgs(signedData);
      (void)NSS_CMSSignedData_GetContentInfo(signedData);
      (void)NSS_CMSSignedData_HasDigests(signedData);
      (void)NSS_CMSSignedData_ContainsCertsOrCrls(signedData);

      (void)NSS_CMSSignedData_ImportCerts(signedData, CERT_GetDefaultCertDB(),
                                          certUsageEmailSigner, PR_FALSE);
      (void)NSS_CMSSignedData_VerifyCertsOnly(
          signedData, CERT_GetDefaultCertDB(), certUsageEmailSigner);

      int si_count = NSS_CMSSignedData_SignerInfoCount(signedData);

      for (int si = 0; si < si_count; si++) {
        NSSCMSSignerInfo* signerInfo =
            NSS_CMSSignedData_GetSignerInfo(signedData, si);

        (void)NSS_CMSSignerInfo_GetVerificationStatus(signerInfo);
        (void)NSS_CMSSignerInfo_GetDigestAlg(signerInfo);
        (void)NSS_CMSSignerInfo_GetDigestAlgTag(signerInfo);
        (void)NSS_CMSSignerInfo_GetCertList(signerInfo);
        (void)NSS_CMSSignerInfo_GetVersion(signerInfo);
        PRTime time;
        (void)NSS_CMSSignerInfo_GetSigningTime(signerInfo, &time);

        char* cn = NSS_CMSSignerInfo_GetSignerCommonName(signerInfo);
        PORT_Free(cn);
        char* email = NSS_CMSSignerInfo_GetSignerEmailAddress(signerInfo);
        PORT_Free(email);

        (void)NSS_CMSSignerInfo_GetSigningCertificate(signerInfo, NULL);

        (void)NSS_CMSSignerInfo_VerifyCertificate(
            signerInfo, CERT_GetDefaultCertDB(), certUsageEmailSigner);
        (void)NSS_CMSSignerInfo_Verify(signerInfo, nullptr, nullptr);
        (void)NSS_CMSSignedData_VerifySignerInfo(
            signedData, si, CERT_GetDefaultCertDB(), certUsageEmailSigner);
      }
    } else if (tag == SEC_OID_PKCS7_ENVELOPED_DATA) {
      NSSCMSEnvelopedData* envData =
          (NSSCMSEnvelopedData*)NSS_CMSContentInfo_GetContent(cinfo);
      if (!envData) {
        continue;
      }
      (void)NSS_CMSEnvelopedData_GetContentInfo(envData);

      NSSCMSRecipientInfo** recipientInfos = envData->recipientInfos;
      if (recipientInfos) {
        for (int ri = 0; recipientInfos[ri] != NULL; ri++) {
          (void)NSS_CMSRecipientInfo_GetVersion(recipientInfos[ri]);
        }
      }
    } else if (tag == SEC_OID_PKCS7_DIGESTED_DATA) {
      NSSCMSDigestedData* digData =
          (NSSCMSDigestedData*)NSS_CMSContentInfo_GetContent(cinfo);
      if (!digData) {
        continue;
      }
      (void)NSS_CMSDigestedData_GetContentInfo(digData);
    } else if (tag == SEC_OID_PKCS7_ENCRYPTED_DATA) {
      NSSCMSEncryptedData* encData =
          (NSSCMSEncryptedData*)NSS_CMSContentInfo_GetContent(cinfo);
      if (!encData) {
        continue;
      }
      (void)NSS_CMSEncryptedData_GetContentInfo(encData);
    }
  }

  (void)NSS_CMSMessage_GetContent(cmsg.get());

  NSS_CMSMessage_GetContentInfo(cmsg.get());

  ScopedNSSCMSMessage copy(NSS_CMSMessage_Copy(cmsg.get()));

  return 0;
}

