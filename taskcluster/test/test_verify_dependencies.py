def digest(content):
    return hashlib.sha256(content).hexdigest()


def write_inventory(directory, name, components):
    """Write an inventory in the shape `--write-verification-metadata` does.

    `components` maps "group:name:version" to {filename: content}, and the
    recorded checksum is that of the content, so a test makes a component
    corrupt or missing by writing something else, or nothing, to the repository.
    """
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">',
        "   <configuration>",
        "      <verify-metadata>true</verify-metadata>",
        "   </configuration>",
        "   <components>",
    ]
    for coordinates, files in components.items():
        group, module, version = coordinates.split(":")
        lines.append(
            f'      <component group="{group}" name="{module}" version="{version}">'
        )
        for filename, content in files.items():
            lines.append(f'         <artifact name="{filename}">')
            lines.append(
                f'            <sha256 value="{digest(content)}" '
                'origin="Generated by Gradle"/>'
            )
            lines.append("         </artifact>")
        lines.append("      </component>")
    lines += ["   </components>", "</verification-metadata>"]

    directory.mkdir(parents=True, exist_ok=True)
    inventory = directory / f"{name}.xml"
    inventory.write_text("\n".join(lines), encoding="utf-8")
    return inventory


def write_raw_inventory(directory, name, body):
    """An inventory written by hand, for shapes the helpers cannot express."""
    directory.mkdir(parents=True, exist_ok=True)
    inventory = directory / f"{name}.xml"
    inventory.write_text(
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">'
        f"<components>{body}</components></verification-metadata>",
        encoding="utf-8",
    )
    return inventory


def write_inventory_without_checksums(directory, name, components):
    """An inventory whose artifacts carry no <sha256>, which verify() can only
    check for existence."""
    body = ""
    for coordinates, files in components.items():
        group, module, version = coordinates.split(":")
        artifacts = "".join(f'<artifact name="{filename}"/>' for filename in files)
        body += (
            f'<component group="{group}" name="{module}" version="{version}">'
            f"{artifacts}</component>"
        )
    return write_raw_inventory(directory, name, body)


def populate(repository, components):
    """Lay components out in a repository the way a Maven repository does."""
    for coordinates, files in components.items():
        group, module, version = coordinates.split(":")
        directory = repository.joinpath(*group.split("."), module, version)
        directory.mkdir(parents=True, exist_ok=True)
        for filename, content in files.items():
            (directory / filename).write_bytes(content)
    return repository


def check(inventories, repositories, unproxied=()):
    inventory, _, _ = verify_dependencies.merge_inventories(sorted(inventories))
    return verify_dependencies.verify(inventory, repositories, unproxied)


def test_complete_tree(tmp_path):
    components = {
        "com.example:widget:1.0": {
            "widget-1.0.jar": b"jar",
            "widget-1.0.pom": b"pom",
        },
        "androidx.core:core:1.2.3": {"core-1.2.3.aar": b"aar"},
    }
    inventory = write_inventory(tmp_path / "inventories", "top-level", components)
    repository = populate(tmp_path / "central", components)

    result = check([inventory], [repository])
    assert (result.problems, result.unpackaged) == ([], [])
    assert (result.artifacts, result.redirected) == (3, 0)


