def test_report_separates_the_kinds_and_their_advice(tmp_path, capsys):
    """Absent and incompletely packaged want different things from the reader."""
    verify_dependencies.report([
        ("absent", ("org.example", "gone", "1.0"), "org/example/gone/1.0"),
        ("missing", ("com.example", "widget", "1.0"), "widget-1.0.jar"),
        ("corrupt", ("com.example", "other", "2.0"), "/packaged/other-2.0.jar"),
    ])
    out = capsys.readouterr().out

    # Treeherder's log parser surfaces the "FATAL ERROR" line and nothing else,
    # so the tally has to be on it. See treeherder/log_parser/parsers.py.
    fatal = [line for line in out.splitlines() if "FATAL ERROR" in line]
    assert fatal == [
        "FATAL ERROR: the packaged dependency cache is incomplete: "
        "1 component absent, 1 file missing, 1 file corrupt."
    ]

    assert "1 component resolved by an enumeration pass" in out
    assert "  absent: org.example:gone:1.0 (looked for org/example/gone/1.0)" in out
    assert "--unproxied" in out

    assert "1 file resolved from a component that is packaged" in out
    assert "  missing: com.example:widget:1.0 -> widget-1.0.jar" in out
    assert "Re-running the task usually produces a complete one." in out

    assert "1 packaged file whose contents do not match" in out
    assert "  corrupt: /packaged/other-2.0.jar" in out


