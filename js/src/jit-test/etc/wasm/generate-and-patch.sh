#!/usr/bin/env bash

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

readme='# Wasm Spec Tests

These tests are autogenerated using a tool, do not edit.

See `jit-test/etc/wasm/` for more information.'

degraded=2

status=0
(cd ./generate-spectests && RUST_BACKTRACE=1 RUST_LOG="${RUST_LOG:-info}" cargo run --release) || status=$?
if [ "$status" -ne 0 ] && [ "$status" -ne "$degraded" ]; then
  exit "$status"
fi

rm -rf ../../tests/wasm/spec
cp -R generate-spectests/tests/js ../../tests/wasm/spec
echo "$readme" > ../../tests/wasm/spec/README.md

if [ -f ./spec-tests.patch ]; then
  (cd ../../tests/wasm/spec && patch -s -u -p7 < ../../../etc/wasm/spec-tests.patch)
fi

exit "$status"
